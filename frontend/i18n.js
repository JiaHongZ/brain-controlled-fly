let currentLang = (() => { try { return localStorage.getItem('neurofly-lang') || 'en'; } catch (e) { return 'en'; } })();

export function t(key) {
  const dict = I18N[currentLang] || I18N.en;
  return dict[key] != null ? dict[key] : (I18N.en[key] != null ? I18N.en[key] : key);
}
export function getLang() { return currentLang; }

function applyStatic() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = t(el.getAttribute('data-i18n'));
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-html'));
    if (v != null) el.innerHTML = v;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-title'));
    if (v != null) el.setAttribute('title', v);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = t(el.getAttribute('data-i18n-placeholder'));
    if (v != null) el.setAttribute('placeholder', v);
  });
}

export function setLang(lang) {
  currentLang = lang === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem('neurofly-lang', currentLang); } catch (e) {}
  applyStatic();
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = t('lang-toggle');
  document.dispatchEvent(new CustomEvent('neurofly-lang', { detail: currentLang }));
}

export function initI18n() {
  applyStatic();
  document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
  const btn = document.getElementById('lang-toggle');
  if (btn) {
    btn.textContent = t('lang-toggle');
    btn.addEventListener('click', () => setLang(currentLang === 'zh' ? 'en' : 'zh'));
  }
}
